/**
 * 从「城市 区县」字符串中解析出规范城市名。
 * @param {string} cityText
 * @returns {string} 归一化后的城市名（去掉尾部「市」）；无内容返回空串
 */
export function normalizeCityName(cityText) {
  const raw = String(cityText || '').trim()
  if (!raw) return ''
  const token = raw.split(/\s+/)[0] || raw
  let name = token.trim()
  if (name.endsWith('特别行政区')) name = name.slice(0, -5)
  else if (name.endsWith('市')) name = name.slice(0, -1)
  return name
}

/**
 * 解析城市中心坐标（活动地图回退用）。
 * @param {string} cityText 活动记录的 city 字段（如「上海市 浦东新区」）
 * @returns {{ latitude: string, longitude: string, city: string } | null}
 */
export function resolveCityCoords(cityText) {
  const name = normalizeCityName(cityText)
  if (!name) return null
  const coords = CITY_COORDS[name]
  if (!coords) return null
  return {
    latitude: String(coords[0]),
    longitude: String(coords[1]),
    city: name
  }
}
