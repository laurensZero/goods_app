export const SQL_FIXTURE_MARKERS = Object.freeze({
  begin: '-- >>> ref-fixtures:begin（generated by scripts/gen-image-ref-fixtures.mjs — 改 fixture 后重跑本脚本，勿手改）',
  end: '-- <<< ref-fixtures:end'
})

/**
 * @param {unknown} value
 * @returns {string}
 */
function sqlText(value) {
  return `'${String(value ?? '').replace(/'/g, "''")}'`
}

/**
 * 生成 SQL 里的 fixture 块（`insert into ref_fixtures ...` 一条语句）。
 * @param {ReadonlyArray<RefFixture>} fixtures
 * @returns {string}
 */
export function buildSqlFixtureBlock(fixtures = REF_FIXTURE_ENTRIES) {
  const rows = fixtures.map((fixture) => (
    `  (${sqlText(fixture.name)}, ${sqlText(JSON.stringify(fixture.entry))}::jsonb, ${sqlText(fixture.expected)})`
  ))
  return [
    SQL_FIXTURE_MARKERS.begin,
    'insert into ref_fixtures (name, entry, expected) values',
    `${rows.join(',\n')};`,
    SQL_FIXTURE_MARKERS.end
  ].join('\n')
}
